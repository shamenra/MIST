using NexusMods.Hashing.xxHash3;
using NexusMods.Sdk.Hashes;

namespace NexusMods.Abstractions.Loadouts.Synchronizers;

/// <summary>
/// Stages new intrinsic content, verifies its bytes, journals publication,
/// then publishes with non-overwriting semantics. The caller must retain
/// the returned journal until its database transaction commits.
///
/// A pending journal requires explicit recovery review after a crash.
/// This does not solve path replacement races by concurrent processes.
/// </summary>
public static class MISTIntrinsicFileWriter
{
    public static async Task<string> WriteJournaledNewFileAsync(
        string destination,
        Func<Stream, Task> write,
        string journalDirectory,
        string installationEntityId,
        CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(destination);
        ArgumentNullException.ThrowIfNull(write);
        ArgumentException.ThrowIfNullOrWhiteSpace(journalDirectory);
        ArgumentException.ThrowIfNullOrWhiteSpace(installationEntityId);
        cancellationToken.ThrowIfCancellationRequested();

        var target = Path.GetFullPath(destination);
        var parent = Path.GetDirectoryName(target)
            ?? throw new IOException("Intrinsic destination has no parent.");
        Directory.CreateDirectory(parent);

        // Only a private sibling file can contain partially generated bytes.
        // Never open the actual destination until publication.
        var staged = Path.Combine(
            parent, $".mist-stage-{Guid.NewGuid():N}");

        // After journaling is attempted, retain the stage in case an
        // unresolved pending record needs it for manual recovery.
        var journalingAttempted = false;
        try
        {
            await using (var stream = new FileStream(
                staged,
                FileMode.CreateNew,
                FileAccess.Write,
                FileShare.None,
                bufferSize: 81920,
                options: FileOptions.Asynchronous))
            {
                await write(stream);
                await stream.FlushAsync(cancellationToken);
                stream.Flush(flushToDisk: true);
            }

            cancellationToken.ThrowIfCancellationRequested();

            // Intrinsic content is generated dynamically, so calculate its
            // actual hash after closing the completed staging stream.
            Hash hash;
            await using (var reader = File.OpenRead(staged))
            {
                hash = (await MultiHasher.HashStream(
                    reader, cancellationToken)).XxHash3;
            }

            var publication = new[]
            {
                (StagedPath: staged,
                 DestinationPath: target,
                 ExpectedHash: hash),
            };

            // Persist recovery evidence before ANY destination publication.
            journalingAttempted = true;
            var pending = await MISTDeploymentJournal.BeginAsync(
                journalDirectory,
                installationEntityId,
                publication,
                cancellationToken);

            // Validates content again, then publishes without overwrite.
            // On failure, the journal and stage are intentionally retained.
            await MISTStagedFilePublisher.PublishNewFilesAsync(
                publication,
                cancellationToken);

            return pending;
        }
        finally
        {
            // Before any journal attempt, the only possible output is the
            // unfinished private stage, which is safe to remove.
            if (!journalingAttempted && File.Exists(staged))
                File.Delete(staged);
        }
    }
}
